import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";
for (const width of [1280, 390]) test(`example enters the recorded world without setup or inference at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 850 });
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  let inference = 0;
  await page.route("**/api/{judge,reflect}", route => { inference++; return route.abort(); });
  await page.goto("/play#example");
  await expect(page.getByRole("region", { name: "Run status", exact: true })).toContainText("Recorded example");
  const bounds = await page.locator("canvas.life-canvas").boundingBox();
  expect(bounds && bounds.y >= 64 && bounds.y + bounds.height <= 850).toBe(true);
  await page.getByRole("button", { name: "Pause", exact: true }).click();
  await expect(page.locator("canvas.life-canvas")).toBeVisible();
  await page.locator(".example-tips summary").click();
  await expect(page.getByText("Pause to look closer.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Dismiss example tips" }).click();
  await expect(page.getByText("Pause to look closer.", { exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Inspect a living organism", exact: true }).click();
  await page.getByRole("button", { name: /Follow founder lineage/ }).click();
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.getByLabel("Playback speed").selectOption("fast");
  await page.getByRole("button", { name: "Resume", exact: true }).click();
  const results = page.getByRole("region", { name: "Run results", exact: true });
  await expect(results).toBeVisible({ timeout: 20000 });
  const example = JSON.parse(readFileSync("public/example-world.json", "utf8"));
  await expect(results).toContainText(`generation ${example.endpoint.generation}`);
  await expect(results).toContainText(`cumulative births: ${example.endpoint.births}; deaths: ${example.endpoint.deaths}; kills: ${example.endpoint.kills}`);
  expect(inference).toBe(0);
  expect(errors).toEqual([]);
});
