import { test, expect } from "@playwright/test";
import { deterministicEvolutionDecision } from "../src/game/decisions";

test("an adaptive trial leads to a separate reviewable fixed baseline and one-condition mobile follow-up", async ({ page }, info) => {
 test.setTimeout(600_000);
 const requests: unknown[] = [], errors: string[] = [];
 page.on("pageerror", error => errors.push(error.message));
 await page.route("**/api/judge", async route => {
  const payload=route.request().postDataJSON(); requests.push(payload);
  if(payload.kind==="evolution") await route.fulfill({json:deterministicEvolutionDecision(payload.summary)});
  else await route.abort();
 });
 await page.setViewportSize({width:1280,height:850});
 await page.goto("/play");
 await page.getByRole("button",{name:"Explore deterministic preset"}).click();
 await page.getByLabel("Your question or prediction (optional)").fill("PRIVATE control question");
 await expect(page.getByLabel("World policy")).toHaveValue("adaptive");
 await page.getByRole("button",{name:/Seed ecosystem/}).click();
 await page.getByRole("button",{name:"3× speed"}).click();
 const results=page.getByRole("region",{name:"Run results",exact:true});
 await expect(results).toBeVisible({timeout:180_000});
 expect(requests.length).toBeGreaterThan(0);
 const previousCalls=requests.length;
 await page.getByRole("button",{name:"Review fixed-rule baseline",exact:true}).click();
 await expect(page.getByText(/Review a separate fixed-rule baseline/)).toBeVisible();
 await expect(page.getByLabel("World policy")).toHaveValue("fixed");
 await expect(page.getByLabel("Your question or prediction (optional)")).toHaveValue("PRIVATE control question");
 await expect(page.getByRole("button",{name:/Seed ecosystem/})).toBeEnabled();
 await expect(page.getByRole("region",{name:"Run status",exact:true})).toHaveCount(0);
 await page.getByRole("button",{name:/Seed ecosystem/}).click();
 await expect(results).toBeVisible({timeout:180_000});
 const comparison=page.getByRole("region",{name:"Previous trial comparison"});
 await expect(comparison).toContainText("Adaptive exploration");
 await expect(comparison).toContainText("Previous policy: adaptive; this trial: fixed");
 expect(requests.length).toBe(previousCalls);
 await page.setViewportSize({width:390,height:850});
 await page.getByRole("button",{name:"Edit this world",exact:true}).click();
 await page.getByText("Edit world conditions",{exact:true}).click();
 await page.getByLabel("Resource abundance").selectOption("scarce");
 await page.getByRole("button",{name:/Seed ecosystem/}).click();
 await expect(results).toBeVisible({timeout:180_000});
 await expect(comparison).toContainText("Resource abundance: rich → scarce");
 await expect(comparison).toContainText("Single-condition fixed comparison");
 await expect(comparison).toContainText("Previous policy: fixed; this trial: fixed");
 expect(requests.length).toBe(previousCalls);
 expect(JSON.stringify(requests)).not.toContain("PRIVATE control question");
 expect(errors).toEqual([]);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
 await page.screenshot({path:info.outputPath("mobile-fixed-comparison.png"),fullPage:true});
});
