import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { Script } from 'node:vm';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'src/observatory');
const result = await build({ entryPoints: [path.join(source, 'entry.js')], bundle: true, write: false, format: 'iife', platform: 'browser' });
const bundle = result.outputFiles[0].text;
new Script(bundle);
const template = await readFile(path.join(source, 'template-v2.html'), 'utf8');
if (template.split('__BUNDLE__').length !== 2) throw new Error('Expected exactly one observatory bundle slot');
const html = template.replace('__BUNDLE__', () => bundle.replace(/<\/script/gi, '<\\/script'));
const generated = '// Generated by scripts/build-observatory.mjs; do not edit.\nexport default ' + JSON.stringify(html) + ';\n';
const destination = path.join(source, 'generated-html.ts');
if (await readFile(destination, 'utf8').catch(() => '') !== generated) await writeFile(destination, generated);
const outputIndex = process.argv.indexOf('--output');
if (outputIndex !== -1) {
  const output = process.argv[outputIndex + 1];
  if (!output) throw new Error('--output requires a file path');
  await mkdir(path.dirname(path.resolve(output)), { recursive: true });
  await writeFile(output, html);
  console.log(path.resolve(output));
}
